"""From immutable run records to the report's figures. Pre-registration section 8.

Every rule this module applies is one the pre-registration fixed before
any trial existed, and the point of putting them here rather than in the
report builder is that they are then testable in isolation:

* **Pairing** is by ``(run_id, task, seed)`` and requires *both* arms to
  have an ``ok`` trial in that exact cell. A half-present cell is
  dropped, never completed with a guess.
* **Errored trials** (``status != "ok"``) carry ``success = null`` in the
  record schema and are excluded from the endpoint, with their rate
  published per arm -- section 8's exclusion rule. They are never
  coerced to failure, because a flaky container is not evidence about an
  arm, and silently counting it as a loss would penalise whichever arm
  happened to run when the host was unhealthy.
* **Saturated tasks** (section 5) are dropped from the primary analysis
  and reported in an appendix. They cannot show an effect and including
  them only dilutes one. The switch is a parameter so the appendix can
  be generated by the same code path.
* **Verdicts are computed** from the CI by :func:`verdict` and never
  written by hand.
"""

from __future__ import annotations

import math
from collections.abc import Iterable, Mapping, Sequence
from dataclasses import dataclass, replace

from ..arms import COMPARISONS, BY_ID, Comparison
from .bootstrap import cluster_bootstrap_diff, task_diffs
from .mcnemar import discordant, mcnemar_exact
from .multiplicity import METHOD as HOLM_METHOD
from .multiplicity import holm_bonferroni
from .wilson import rate, wilson_interval

Record = Mapping[str, object]
Pairs = list[list[tuple[bool, bool]]]

#: Below this many usable pairs a comparison reports ``insufficient-data``
#: rather than a verdict. Section 8 fixes no such threshold, so this is a
#: *declared* default rather than a pre-registered one: it exists because
#: the verdict rule has to be total, and a CI from three pairs that
#: happens to exclude 0 should not be published as support. Record the
#: value used next to the figure; override it per run if the pilot says so.
DEFAULT_MIN_PAIRS = 10

#: A cluster bootstrap over one task cannot estimate between-task
#: variance -- the only quantity it exists to estimate.
MIN_TASKS = 2

P_METHOD = "mcnemar-exact"
CI_PREFIX = "cluster-bootstrap-tasks"
DIMENSIONS = ("headroom_band", "discoverability", "tier", "video_tier")
_ORDER: dict[str, tuple[str, ...]] = {
    "headroom_band": ("high", "medium", "low", "saturated", "unknown"),
    "discoverability": ("good", "poor", "unknown"),
    "video_tier": ("hermetic", "real", "unknown"),
}


@dataclass(frozen=True)
class ComparisonResult:
    """One row of the report's ``comparisons`` array."""

    hypothesis: str
    treatment: str
    reference: str
    verdict: str
    claim: str = ""
    fails_if: str = ""
    n_pairs: int = 0
    n_tasks: int = 0
    diff: float | None = None
    ci_lo: float | None = None
    ci_hi: float | None = None
    ci_method: str = "none"
    discordant_b: int | None = None
    discordant_c: int | None = None
    p_value: float | None = None
    p_adjusted: float | None = None
    p_method: str = P_METHOD
    pooled_diff: float | None = None
    corrected: bool = False
    resamples: int = 0
    seed: int = 0
    fallback_reason: str | None = None


@dataclass(frozen=True)
class ArmSummary:
    """One row of the report's ``arms`` array."""

    id: str
    name: str
    n: int
    successes: int
    rate: float
    wilson_lo: float
    wilson_hi: float
    error_rate: float
    isolates: str = ""
    description: str = ""
    mean_usd: float | None = None
    mean_turns: float | None = None
    mean_wall_secs: float | None = None
    policy_violation_rate: float | None = None
    key_action_hit_rate: float | None = None
    status_counts: Mapping[str, int] | None = None


@dataclass(frozen=True)
class CellSummary:
    """One cell of the report's task x arm grid."""

    task: str
    arm: str
    n: int
    successes: int
    errors: int
    rate: float
    wilson_lo: float
    wilson_hi: float
    mean_turns: float | None = None
    mean_usd: float | None = None
    key_action_hit_rate: float | None = None
    skill_cited_rate: float | None = None


@dataclass(frozen=True)
class StratumResult:
    """One row of the report's ``strata`` array (hypothesis H2)."""

    dimension: str
    value: str
    treatment: str
    reference: str
    n_pairs: int
    n_tasks: int
    diff: float | None = None
    ci_lo: float | None = None
    ci_hi: float | None = None
    ci_method: str = "none"


def _sub(record: Record, key: str) -> Mapping[str, object]:
    value = record.get(key)
    return value if isinstance(value, Mapping) else {}


def _status(record: Record) -> str:
    status = _sub(record, "outcome").get("status")
    return status if isinstance(status, str) else "missing"


def _success(record: Record) -> bool:
    value = _sub(record, "outcome").get("success")
    if not isinstance(value, bool):
        raise ValueError(
            f"record {record.get('trial_id')!r} has status 'ok' but success={value!r}; "
            "an ok trial must record a boolean outcome"
        )
    return value


def _saturated(record: Record) -> bool:
    task = _sub(record, "task")
    return bool(task.get("saturated")) or task.get("headroom_band") == "saturated"


def _mean(values: Iterable[float]) -> float | None:
    seq = list(values)
    return math.fsum(seq) / len(seq) if seq else None


def _metric_mean(records: Sequence[Record], key: str) -> float | None:
    return _mean(
        float(v)
        for r in records
        if isinstance(v := _sub(r, "metrics").get(key), (int, float)) and not isinstance(v, bool)
    )


def _flag_rate(records: Sequence[Record], key: str) -> float | None:
    flags = [v for r in records if isinstance(v := _sub(r, "metrics").get(key), bool)]
    return sum(flags) / len(flags) if flags else None


def refuse_mixed(records: Sequence[Record]) -> bool:
    """Raise if mock and measured records appear together; return True if all mock.

    Mock records come from the stub agent and contain invented outcomes.
    Aggregating even one of them into a figure would mean publishing a
    fabricated number under the provenance of a real run, which the
    record schema calls out explicitly and which no amount of later
    labelling undoes. The report's ``status.kind`` of ``mock`` exists for
    the all-mock case, so the return value tells the builder which banner
    to render; the mixed case has no honest rendering and must stop the
    build.
    """
    mock = [bool(_sub(r, "provenance").get("is_mock", False)) for r in records]
    if any(mock) and not all(mock):
        examples = [r.get("trial_id") for r, m in zip(records, mock, strict=True) if m][:3]
        raise ValueError(
            f"refusing to aggregate {sum(mock)} mock record(s) with "
            f"{len(mock) - sum(mock)} measured record(s); e.g. {examples}. "
            "Mock and measured data are never combined into one figure."
        )
    return bool(mock) and all(mock)


def pair_trials(
    records: Sequence[Record],
    treatment: str,
    reference: str,
    include_saturated: bool = False,
) -> Pairs:
    """Group ``ok`` trials into one list of paired outcomes per task.

    A pair exists only where both arms have an ``ok`` trial for the same
    ``(run_id, task, seed)``. ``run_id`` is part of the key because
    re-running a frozen suite is "a new row, never an edit" (section 8.2),
    so two runs legitimately contain the same (task, seed) and pairing
    across them would invent comparisons that were never run against the
    same material. Tasks are returned in id order and pairs within a task
    in ``(run_id, seed)`` order, so the bootstrap's draw sequence is a
    function of the data and not of dict iteration order.
    """
    if treatment == reference:
        raise ValueError(f"treatment and reference must differ, both are {treatment!r}")

    cells: dict[tuple[str, str, int], dict[str, bool]] = {}
    for record in records:
        arm = record.get("arm")
        if arm not in (treatment, reference):
            continue
        if not include_saturated and _saturated(record):
            continue
        if _status(record) != "ok":
            continue
        task_id = _sub(record, "task").get("id")
        run_id = record.get("run_id")
        seed = record.get("seed")
        if not isinstance(task_id, str) or not isinstance(run_id, str):
            raise ValueError(f"record {record.get('trial_id')!r} lacks a task id or run_id")
        if not isinstance(seed, int) or isinstance(seed, bool):
            raise ValueError(f"record {record.get('trial_id')!r} has a non-integer seed {seed!r}")
        slot = cells.setdefault((task_id, run_id, seed), {})
        if arm in slot:
            raise ValueError(
                f"duplicate ok trial for task={task_id} run={run_id} seed={seed} arm={arm}; "
                "records are append-only and one cell must appear once"
            )
        slot[str(arm)] = _success(record)

    clusters: dict[str, list[tuple[bool, bool]]] = {}
    for (task_id, _run, _seed), slot in sorted(cells.items()):
        if treatment in slot and reference in slot:
            clusters.setdefault(task_id, []).append((slot[treatment], slot[reference]))
    return [clusters[task_id] for task_id in sorted(clusters)]


def verdict(
    n_pairs: int,
    n_tasks: int,
    ci_lo: float | None,
    ci_hi: float | None,
    arms_present: bool = True,
    min_pairs: int = DEFAULT_MIN_PAIRS,
) -> str:
    """The pre-registered decision rule, in one place, applied to every row.

    Exactly as declared: ``insufficient-data`` when the evidence is too
    thin to decide or an arm was never run; ``supported`` when the CI
    excludes 0 on the hypothesised side; ``not-supported`` when it
    excludes 0 on the *opposite* side -- a result we commit to publishing
    (section 10) -- and ``inconclusive`` whenever the CI contains 0.

    Every pre-registered comparison in ``arms.py`` is directional with the
    treatment hypothesised *above* the reference, so "the hypothesised
    direction" is ``ci_lo > 0``. A future comparison that reverses that
    would need its direction declared in ``arms.py`` first; it is not a
    choice the stats layer may make after seeing data.
    """
    if not arms_present or n_pairs < min_pairs or n_tasks < MIN_TASKS:
        return "insufficient-data"
    if ci_lo is None or ci_hi is None:
        return "insufficient-data"
    if ci_lo > 0.0:
        return "supported"
    if ci_hi < 0.0:
        return "not-supported"
    return "inconclusive"


def _interval(
    clusters: Pairs, resamples: int, seed: int, ci: float, method: str
) -> tuple[int, int, float | None, float | None, float | None, float | None, str, str | None]:
    """Shared point-estimate-and-CI path for comparisons and strata."""
    if not clusters:
        return (0, 0, None, None, None, None, "none", None)
    diffs, n_pairs, pooled = task_diffs(clusters)
    point = math.fsum(diffs) / len(diffs)
    if len(diffs) < MIN_TASKS:
        return (n_pairs, len(diffs), point, pooled, None, None,
                f"none ({MIN_TASKS} tasks needed to resample tasks)", None)
    boot = cluster_bootstrap_diff(clusters, resamples=resamples, seed=seed, ci=ci, method=method)
    return (n_pairs, len(diffs), boot.point, boot.pooled_point, boot.ci_lo, boot.ci_hi,
            f"{CI_PREFIX}-{boot.ci_method}", boot.fallback_reason)


def analyse_comparison(
    records: Sequence[Record],
    comparison: Comparison,
    resamples: int = 10000,
    seed: int = 0,
    ci: float = 0.95,
    method: str = "bca",
    min_pairs: int = DEFAULT_MIN_PAIRS,
    include_saturated: bool = False,
) -> ComparisonResult:
    """Analyse one pre-registered comparison. ``p_adjusted`` is filled in by
    :func:`analyse_comparisons`, which knows the whole Holm family."""
    arms_seen = {r.get("arm") for r in records}
    present = comparison.treatment in arms_seen and comparison.reference in arms_seen
    clusters = pair_trials(
        records, comparison.treatment, comparison.reference, include_saturated=include_saturated
    )
    n_pairs, n_tasks, diff, pooled, lo, hi, ci_method, fallback = _interval(
        clusters, resamples, seed, ci, method
    )
    flat = [pair for cluster in clusters for pair in cluster]
    b, c = discordant(flat)
    return ComparisonResult(
        hypothesis=comparison.hypothesis,
        treatment=comparison.treatment,
        reference=comparison.reference,
        verdict=verdict(n_pairs, n_tasks, lo, hi, arms_present=present, min_pairs=min_pairs),
        claim=comparison.claim,
        fails_if=comparison.fails_if,
        n_pairs=n_pairs,
        n_tasks=n_tasks,
        diff=diff,
        ci_lo=lo,
        ci_hi=hi,
        ci_method=ci_method,
        discordant_b=b if flat else None,
        discordant_c=c if flat else None,
        p_value=mcnemar_exact(b, c) if flat else None,
        pooled_diff=pooled,
        corrected=comparison.corrected,
        resamples=resamples,
        seed=seed,
        fallback_reason=fallback,
    )


def analyse_comparisons(
    records: Sequence[Record],
    comparisons: Sequence[Comparison] = COMPARISONS,
    **kwargs: object,
) -> list[ComparisonResult]:
    """Analyse every comparison, then Holm-correct exactly the flagged family.

    Membership is ``Comparison.corrected`` and nothing else, so H1 -- the
    single declared primary endpoint -- keeps its uncorrected p-value
    while the ablations pay for being a family. A comparison with no
    p-value (no usable pairs) cannot be in the family either; the family
    size actually used is written into ``p_method`` so the reader does
    not have to count the rows.
    """
    results = [analyse_comparison(records, c, **kwargs) for c in comparisons]  # type: ignore[arg-type]
    family = {r.hypothesis: r.p_value for r in results if r.corrected and r.p_value is not None}
    adjusted = holm_bonferroni(family)
    method = f"{P_METHOD}; {HOLM_METHOD}(m={len(family)})"
    return [
        replace(r, p_adjusted=adjusted[r.hypothesis], p_method=method)
        if r.hypothesis in adjusted
        else r
        for r in results
    ]


def analyse_arms(records: Sequence[Record]) -> list[ArmSummary]:
    """Per-arm rates, error rates and secondary means for the report's ``arms``.

    ``error_rate`` is the fraction of this arm's trials with any
    non-``ok`` status, not just ``status == "error"``. Section 8 names
    only ``error``, but the record schema leaves ``success`` null for
    ``timeout``, ``budget_exceeded`` and ``refused`` as well, so none of
    those can enter the endpoint either and a reader needs one number for
    "trials that produced no measurement". ``status_counts`` breaks it
    down so a timeout-heavy arm is not mistaken for a flaky one.

    Saturated tasks are *included* here: these are descriptive per-arm
    rates, and section 5 excludes saturated tasks from the primary
    *endpoint*, not from the description of what was run.
    """
    by_arm: dict[str, list[Record]] = {}
    for record in records:
        arm = record.get("arm")
        if isinstance(arm, str):
            by_arm.setdefault(arm, []).append(record)

    summaries: list[ArmSummary] = []
    for arm_id in sorted(by_arm):
        trials = by_arm[arm_id]
        counts: dict[str, int] = {}
        for record in trials:
            status = _status(record)
            counts[status] = counts.get(status, 0) + 1
        ok = [r for r in trials if _status(r) == "ok"]
        successes = sum(1 for r in ok if _success(r))
        lo, hi = wilson_interval(successes, len(ok))
        arm = BY_ID.get(arm_id)
        violations = [
            bool(_sub(r, "metrics").get("policy_violations")) for r in ok
        ]
        summaries.append(
            ArmSummary(
                id=arm_id,
                name=arm.name if arm else arm_id,
                n=len(ok),
                successes=successes,
                rate=rate(successes, len(ok)),
                wilson_lo=lo,
                wilson_hi=hi,
                error_rate=(len(trials) - len(ok)) / len(trials) if trials else 0.0,
                isolates=arm.isolates if arm else "",
                description=arm.description if arm else "",
                mean_usd=_metric_mean(ok, "usd_cost"),
                mean_turns=_metric_mean(ok, "turns"),
                mean_wall_secs=_metric_mean(ok, "wall_secs"),
                policy_violation_rate=(sum(violations) / len(violations)) if violations else None,
                key_action_hit_rate=_flag_rate(ok, "key_action_hit"),
                status_counts=dict(sorted(counts.items())),
            )
        )
    return summaries


def analyse_cells(records: Sequence[Record]) -> list[CellSummary]:
    """The task x arm grid: one cell per combination actually run."""
    by_cell: dict[tuple[str, str], list[Record]] = {}
    for record in records:
        task_id = _sub(record, "task").get("id")
        arm = record.get("arm")
        if isinstance(task_id, str) and isinstance(arm, str):
            by_cell.setdefault((task_id, arm), []).append(record)

    cells: list[CellSummary] = []
    for (task_id, arm_id) in sorted(by_cell):
        trials = by_cell[(task_id, arm_id)]
        ok = [r for r in trials if _status(r) == "ok"]
        successes = sum(1 for r in ok if _success(r))
        lo, hi = wilson_interval(successes, len(ok))
        cells.append(
            CellSummary(
                task=task_id,
                arm=arm_id,
                n=len(ok),
                successes=successes,
                errors=len(trials) - len(ok),
                rate=rate(successes, len(ok)),
                wilson_lo=lo,
                wilson_hi=hi,
                mean_turns=_metric_mean(ok, "turns"),
                mean_usd=_metric_mean(ok, "usd_cost"),
                key_action_hit_rate=_flag_rate(ok, "key_action_hit"),
                skill_cited_rate=_flag_rate(ok, "skill_cited"),
            )
        )
    return cells


def _stratum_value(record: Record, dimension: str) -> str:
    if dimension == "video_tier":
        value = _sub(record, "video").get("tier")
    else:
        value = _sub(record, "task").get(dimension)
    return value if isinstance(value, str) and value else "unknown"


def analyse_strata(
    records: Sequence[Record],
    dimension: str,
    treatment: str,
    reference: str,
    resamples: int = 10000,
    seed: int = 0,
    ci: float = 0.95,
    method: str = "bca",
    include_saturated: bool = False,
) -> list[StratumResult]:
    """Effect size within each stratum of one dimension -- hypothesis H2.

    H2 is the claim a reader deciding whether to run v2s actually needs:
    the benefit should be concentrated where the model lacks the
    knowledge. We report the effect *within* each band rather than a
    band x arm interaction statistic, because with three or four bands of
    four to six tasks each an interaction test has no power worth
    quoting, while the per-band intervals show the pattern (or its
    absence) directly and let a reader judge the overlap themselves. That
    is a deliberate departure from a formal interaction test and is
    called out as such in the report.

    Each band is bootstrapped over its *own* tasks, so a band with one
    task reports a point estimate and no interval rather than a
    zero-width one.
    """
    if dimension not in DIMENSIONS:
        raise ValueError(f"dimension must be one of {DIMENSIONS}, got {dimension!r}")

    groups: dict[str, list[Record]] = {}
    for record in records:
        groups.setdefault(_stratum_value(record, dimension), []).append(record)

    order = _ORDER.get(dimension)
    keys = (
        [k for k in order if k in groups] + sorted(set(groups) - set(order))
        if order
        else sorted(groups)
    )
    out: list[StratumResult] = []
    for key in keys:
        clusters = pair_trials(
            groups[key], treatment, reference, include_saturated=include_saturated
        )
        n_pairs, n_tasks, diff, _pooled, lo, hi, ci_method, _fb = _interval(
            clusters, resamples, seed, ci, method
        )
        out.append(
            StratumResult(
                dimension=dimension,
                value=key,
                treatment=treatment,
                reference=reference,
                n_pairs=n_pairs,
                n_tasks=n_tasks,
                diff=diff,
                ci_lo=lo,
                ci_hi=hi,
                ci_method=ci_method,
            )
        )
    return out
